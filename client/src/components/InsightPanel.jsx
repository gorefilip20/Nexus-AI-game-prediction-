import { useId, useState } from 'react';
import { Brain, ChevronDown, Info, TrendingUp } from 'lucide-react';

const CATEGORY_ORDER = ['Model', 'Team form', 'Head-to-head', 'Expected value'];

function groupBullets(bullets = []) {
  const groups = new Map();
  for (const bullet of bullets) {
    if (!groups.has(bullet.category)) groups.set(bullet.category, []);
    groups.get(bullet.category).push(bullet.text);
  }

  return CATEGORY_ORDER.filter((category) => groups.has(category)).map((category) => ({
    category,
    texts: groups.get(category),
  }));
}

function ValueTable({ value, homeName, awayName }) {
  const labels = { Home: homeName, Draw: 'Draw', Away: awayName };

  return (
    <div className="-mx-1 overflow-x-auto px-1">
      <table className="w-full min-w-[320px] border-collapse text-left text-[11px]">
        <thead>
          <tr className="border-b border-[#213743] text-[10px] uppercase tracking-wider text-[#8a96a3]">
            <th scope="col" className="py-1.5 pr-3">Outcome</th>
            <th scope="col" className="py-1.5 pr-3">Price</th>
            <th scope="col" className="py-1.5 pr-3">Model</th>
            <th scope="col" className="py-1.5 pr-3">Market</th>
            <th scope="col" className="py-1.5 pr-3">Gap</th>
            <th scope="col" className="py-1.5">EV</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-[#213743]/60">
          {value.outcomes.map((outcome) => {
            const positive = outcome.expectedValue > 0;
            return (
              <tr key={outcome.label} className="text-[#b1b6c0]">
                <td className="py-1.5 pr-3 font-semibold text-white">
                  {labels[outcome.label] ?? outcome.label}
                </td>
                <td className="py-1.5 pr-3 font-mono">{outcome.odd}</td>
                <td className="py-1.5 pr-3">{outcome.modelProbability}%</td>
                <td className="py-1.5 pr-3">
                  {outcome.marketProbability === null ? '—' : `${outcome.marketProbability}%`}
                </td>
                <td className="py-1.5 pr-3">
                  {outcome.gap === null ? '—' : `${outcome.gap > 0 ? '+' : ''}${outcome.gap}`}
                </td>
                <td className={`py-1.5 font-bold ${positive ? 'text-[#00e701]' : 'text-[#8a96a3]'}`}>
                  {positive ? '+' : ''}
                  {outcome.expectedValue}%
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}

/**
 * The expandable "AI Insight & Analysis" panel.
 *
 * Everything rendered here is generated by the server's rule-based generator
 * from the fitted model, that league's real results and the live odds ladder.
 * The provenance line says so, because "AI Insight" would otherwise imply a
 * narrative written by a language model rather than derived from the numbers.
 */
export default function InsightPanel({ insight, homeName, awayName }) {
  const [expanded, setExpanded] = useState(false);
  const panelId = useId();

  if (!insight) return null;

  const groups = groupBullets(insight.bullets);

  return (
    <div className="mb-4 overflow-hidden rounded-lg border border-[#213743] bg-[#0f212e]">
      <button
        type="button"
        onClick={() => setExpanded((v) => !v)}
        aria-expanded={expanded}
        aria-controls={panelId}
        className="flex min-h-[44px] w-full items-center justify-between px-3 py-2.5 text-left transition hover:bg-[#213743]/30"
      >
        <span className="flex items-center gap-2">
          <Brain className="h-4 w-4 text-[#00e701]" />
          <span className="text-xs font-black uppercase tracking-wider text-white">
            AI Insight &amp; Analysis
          </span>
        </span>
        <ChevronDown
          className={`h-4 w-4 shrink-0 text-[#8a96a3] transition ${expanded ? 'rotate-180' : ''}`}
        />
      </button>

      {expanded ? (
        <div id={panelId} className="space-y-4 border-t border-[#213743] px-3 py-3">
          {groups.map((group) => (
            <div key={group.category}>
              <h4 className="mb-1.5 text-[10px] font-bold uppercase tracking-wider text-[#8a96a3]">
                {group.category}
              </h4>
              <ul className="space-y-1.5">
                {group.texts.map((text) => (
                  <li key={text} className="flex gap-2 text-[11px] leading-relaxed text-[#b1b6c0]">
                    <span className="mt-1.5 h-1 w-1 shrink-0 rounded-full bg-[#00e701]" />
                    <span>{text}</span>
                  </li>
                ))}
              </ul>
            </div>
          ))}

          {insight.value ? (
            <div>
              <h4 className="mb-1.5 flex items-center gap-1.5 text-[10px] font-bold uppercase tracking-wider text-[#8a96a3]">
                <TrendingUp className="h-3 w-3" />
                Value against the book
              </h4>
              <ValueTable value={insight.value} homeName={homeName} awayName={awayName} />
            </div>
          ) : null}

          {insight.caveats?.length ? (
            <div className="rounded-md border border-amber-500/25 bg-amber-500/5 p-2.5">
              <ul className="space-y-1">
                {insight.caveats.map((caveat) => (
                  <li
                    key={caveat}
                    className="flex gap-2 text-[10px] leading-relaxed text-amber-200/85"
                  >
                    <Info className="mt-0.5 h-3 w-3 shrink-0" />
                    <span>{caveat}</span>
                  </li>
                ))}
              </ul>
            </div>
          ) : null}

          <p className="border-t border-[#213743] pt-2 text-[10px] leading-relaxed text-[#8a96a3]">
            Generated by a rule-based engine from the fitted model, this league's finished
            results and the live odds ladder. No part of this text is written by a language
            model, and none of it is advice.
          </p>
        </div>
      ) : null}
    </div>
  );
}
